// Лёгкая нормализация: «ё»→«е», русские «а в с е н» приравниваются к латинским, чтобы «А-101» находилось любой раскладкой.
export const norm = (s: string) =>
  String(s).toLowerCase().replace(/ё/g, 'е').replace(/а/g, 'a').replace(/в/g, 'b').replace(/с/g, 'c').replace(/е/g, 'e').replace(/н/g, 'h')

export const plural = (n: number, f: [string, string, string]) => {
  const m = n % 100, d = n % 10
  return n + ' ' + (m > 10 && m < 15 ? f[2] : d === 1 ? f[0] : d > 1 && d < 5 ? f[1] : f[2])
}
